"""
Converts assets/flipdev.svg into a run-length encoded 4-bit alpha mask for
the firmware (src/logo.h). Needs rsvg-convert and Pillow.

Usage: python3 -I tools/gen_logo.py [size]

Encoding: each byte is (alpha << 4) | (run - 1), alpha 0..15, run 1..16,
rows are concatenated (runs may cross row ends).
"""
import io
import os
import subprocess
import sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SIZE = int(sys.argv[1]) if len(sys.argv) > 1 else 176

png = subprocess.run(
    ["rsvg-convert", "-w", str(SIZE * 4), "-h", str(SIZE * 4),
     os.path.join(ROOT, "assets", "flipdev.svg")],
    check=True, capture_output=True).stdout
img = Image.open(io.BytesIO(png)).convert("RGBA")
# the logo is drawn in black on transparent: coverage = alpha channel
alpha = img.getchannel("A")
bbox = alpha.getbbox()
alpha = alpha.crop(bbox)
w, h = alpha.size
scale = SIZE / max(w, h)
alpha = alpha.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
w, h = alpha.size

px = [min(15, (v + 8) // 17) for v in alpha.tobytes()]
out = []
i = 0
while i < len(px):
    v = px[i]
    run = 1
    while i + run < len(px) and px[i + run] == v and run < 16:
        run += 1
    out.append((v << 4) | (run - 1))
    i += run

lines = [
    "// Generated by tools/gen_logo.py from assets/flipdev.svg - do not edit.",
    "#pragma once",
    "#include <stdint.h>",
    "",
    f"constexpr int16_t LOGO_W = {w};",
    f"constexpr int16_t LOGO_H = {h};",
    f"// {len(out)} bytes, 4-bit alpha run-length encoded",
    "static const uint8_t LOGO_RLE[] = {",
]
for k in range(0, len(out), 16):
    lines.append("  " + ", ".join(f"0x{b:02X}" for b in out[k:k + 16]) + ",")
lines.append("};")
with open(os.path.join(ROOT, "src", "logo.h"), "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"logo {w}x{h}, {len(out)} bytes")
